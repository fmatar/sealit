function resolveUserFileTarget(filePath, allowedRoot = null, warnings = []) {
  if (allowedRoot) assertNoSymlinkAncestors(allowedRoot, path.dirname(filePath));
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const st = fs.lstatSync(filePath, { throwIfNoEntry: false });
  if (!st || !st.isSymbolicLink()) return filePath;
  try {
    const realTarget = fs.realpathSync(filePath);
    const realRoot = allowedRoot ? fs.realpathSync(path.resolve(allowedRoot)) : null;
    if (realRoot) {
      const rel = path.relative(realRoot, realTarget);
      if (rel && !rel.startsWith('..') && !path.isAbsolute(rel)) {
        assertNoSymlinkAncestors(realRoot, path.dirname(realTarget));
        return realTarget;
      }
    }
  } catch {}
  fs.unlinkSync(filePath);
  warnings.push(`Replaced symlink '${path.basename(filePath)}' (target outside allowed root) with a regular file.`);
  return filePath;
}

export function upsertGitignore(targetDir = '.', { warnings = [] } = {}) {
  const absTarget = path.resolve(targetDir);
  const resolvedPath = resolveUserFileTarget(path.join(absTarget, '.gitignore'), absTarget, warnings);
  const exists = fileExists(resolvedPath);
  const raw = exists ? fs.readFileSync(resolvedPath, 'utf8') : '';
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const lineSet = new Set(raw.split(/\r?\n/).map((l) => l.trim()));
  const missing = SDLC_GITIGNORE_ENTRIES.filter((entry) => !lineSet.has(entry));
  if (missing.length === 0 && exists) {
    return { updated: false, added: [], path: resolvedPath };
  }
  const block = `# Agentic SDLC local state & secrets (managed)${eol}${missing.join(eol)}${eol}`;
  const trimmed = raw.trimEnd();
  const next = trimmed ? `${trimmed}${eol}${eol}${block}` : block;
  const effectiveRoot = resolvedPath !== path.join(absTarget, '.gitignore') ? fs.realpathSync(absTarget) : absTarget;
  assertNoSymlinkAncestors(effectiveRoot, path.dirname(resolvedPath));
  writeFileAtomic(resolvedPath, next);
  return { updated: true, added: missing, path: resolvedPath };
}

export function inspectGitignore(repoRoot = '.') {
  const absRoot = path.resolve(repoRoot);
  const rawPath = path.join(absRoot, '.gitignore');
  let content = null;
  try {
    const st = fs.lstatSync(rawPath, { throwIfNoEntry: false });
    if (st?.isSymbolicLink()) {
      const realTarget = fs.realpathSync(rawPath);
      const realRoot = fs.realpathSync(absRoot);
      const rel = path.relative(realRoot, realTarget);
      if (rel && !rel.startsWith('..') && !path.isAbsolute(rel)) {
        content = fs.readFileSync(realTarget, 'utf8');
      }
    } else if (st?.isFile()) {
      content = fs.readFileSync(rawPath, 'utf8');
    }
  } catch {}
  const lineSet = new Set(String(content || '').split(/\r?\n/).map((l) => l.trim()));
  const missing = SDLC_GITIGNORE_ENTRIES.filter((entry) => !lineSet.has(entry));
  return {
    exists: content !== null,
    upToDate: missing.length === 0,
    criticalOk: !missing.includes('.agent/.receipt-key') && !missing.includes('.agent/.sdlc-session.json'),
    missing
  };
}

function upsertMarkedRulesFile(filePath, rulesBlock, baseRoot = null, warnings = []) {
  const resolvedPath = resolveUserFileTarget(filePath, baseRoot, warnings);
  const effectiveRoot = resolvedPath !== filePath && baseRoot ? fs.realpathSync(path.resolve(baseRoot)) : baseRoot;
  if (fileExists(resolvedPath)) {
    const existing = fs.readFileSync(resolvedPath, 'utf8');
    if (existing.includes('<!-- AGENTIC-SDLC-RULES:START -->') && existing.includes('<!-- AGENTIC-SDLC-RULES:END -->')) {
      const updated = existing.replace(/<!-- AGENTIC-SDLC-RULES:START -->[\s\S]*?<!-- AGENTIC-SDLC-RULES:END -->/, rulesBlock);
      safeWriteFile(resolvedPath, updated.endsWith('\n') ? updated : `${updated}\n`, undefined, effectiveRoot);
      return;
    }
    safeWriteFile(resolvedPath, `${existing.trimEnd()}\n\n${rulesBlock}\n`, undefined, effectiveRoot);
    return;
  }
  safeWriteFile(resolvedPath, `${rulesBlock}\n`, undefined, effectiveRoot);
}

function adaptSkillContent(rawMarkdown, agent, { globalEnginePath = null } = {}) {
  let out = String(rawMarkdown || '').replace(/\r\n/g, '\n');
  if (agent !== 'antigravity') {
    out = out.replace(/^tools:\s*.*\n/m, '');
  }
  if (agent === 'claude') {
    out = out.replace(/`invoke_subagent`/g, '`Task`').replace(/\binvoke_subagent\b/g, 'Task');
  } else if (agent === 'cursor' || agent === 'codex' || agent === 'copilot') {
    out = out.replace(/`invoke_subagent`/g, '`subagent`').replace(/\binvoke_subagent\b/g, 'subagent');
  }
  if (globalEnginePath) {
    out = out.replace(/node \.agent\/scripts\/sdlc-engine\.mjs/g, `node "${globalEnginePath}"`);
  }
  return out;
}

export function auditSkills(repoRoot = '.') {
  const skillsDir = path.resolve(repoRoot, '.agent/skills');
  const findings = [];
  if (!fileExists(skillsDir)) {
    return {
      passed: false,
      skillsCount: 0,
      findings: [{ skill: '*', rule: 'DIR_MISSING', message: 'Missing .agent/skills directory.' }]
    };
  }

  for (const id of CANONICAL_SKILLS) {
    const skillPath = path.join(skillsDir, id, 'SKILL.md');
    if (!fileExists(skillPath)) {
      findings.push({ skill: id, rule: 'SKILL_MISSING', message: `Missing canonical skill '${id}/SKILL.md'.` });
      continue;
    }
    const raw = fs.readFileSync(skillPath, 'utf8').replace(/\r\n/g, '\n');
    const linesCount = raw.split('\n').length;
    const { frontmatter, body } = parseFrontmatter(raw);

    if (!frontmatter.name || frontmatter.name !== id) {
      findings.push({ skill: id, rule: 'FM1', message: `Frontmatter 'name' must equal '${id}'.` });
    }
    const desc = String(frontmatter.description || '');
    if (!desc || desc.length > 220 || !/\bUse when\b/i.test(desc)) {
      findings.push({
        skill: id,
        rule: 'FM2',
        message: `Frontmatter 'description' in '${id}' must be <=220 chars and start/include 'Use when'.`
      });
    }
    if (linesCount > 160) {
      findings.push({ skill: id, rule: 'LEN1', message: `Skill '${id}' exceeds 160 lines (${linesCount}).` });
    }

    for (const m of body.matchAll(/\bnpx\s+(?:--yes\s+|-y\s+)?(@?[a-z0-9._/-]+)(?![@\w.-])/gi)) {
      const pkg = m[1];
      if (pkg === '@fmatar/agentic-sdlc') continue;
      findings.push({ skill: id, rule: 'RP1', message: `Unpinned npx package '${pkg}' in '${id}/SKILL.md'.` });
    }

    if (/\.\.\/sdlc-[a-z0-9-]+\/SKILL\.md/i.test(body)) {
      findings.push({ skill: id, rule: 'AS3', message: `Cross-skill relative file link detected in '${id}/SKILL.md'.` });
    }
  }

  return {
    passed: findings.length === 0,
    skillsCount: CANONICAL_SKILLS.length,
    findings
  };
}

function detectNodeCache(repoRoot = null) {
  if (!repoRoot) return null;
  const has = (f) => fileExists(path.resolve(repoRoot, f));
  if (has('package-lock.json') || has('npm-shrinkwrap.json')) return 'npm';
  if (has('pnpm-lock.yaml')) return 'pnpm';
  if (has('yarn.lock')) return 'yarn';
  return null;
}

export function buildQualityGateWorkflow({
  runsOn = "${{ vars.SDLC_RUNS_ON || 'ubuntu-latest' }}",
  checkName = DEFAULT_QUALITY_GATE_CHECK,
  repoRoot = null
} = {}) {
  const runsOnYaml = Array.isArray(runsOn) ? JSON.stringify(runsOn) : runsOn;
  const safeCheckName = String(checkName || DEFAULT_QUALITY_GATE_CHECK).replace(/[\r\n]+/g, ' ');
  const nodeCache = detectNodeCache(repoRoot);
  const cacheLine = nodeCache ? `\n          cache: '${nodeCache}'` : '';
  return `name: SDLC Quality Gate

on:
  push:
    branches: [main, develop]
  pull_request:
    branches: [main, develop]

permissions:
  contents: read

concurrency:
  group: sdlc-gate-\${{ github.ref }}
  cancel-in-progress: true

jobs:
  quality-gate:
    name: ${JSON.stringify(safeCheckName)}
    runs-on: ${runsOnYaml}

    steps:
      - name: Require Self-Hosted Runner Policy
        if: github.repository == 'fmatar/agentic-sdlc-framework' && runner.environment == 'github-hosted'
        run: |
          echo "::error::This repository must run exclusively on self-hosted runners (configure vars.SDLC_RUNS_ON)."
          exit 1

      - name: Block Unverified Fork Pull Requests
        if: github.event_name == 'pull_request' && github.event.pull_request.head.repo.full_name != github.repository
        env:
          PR_HEAD_REPO: \${{ github.event.pull_request.head.repo.full_name }}
        run: |
          echo "::error::Fork pull request ($PR_HEAD_REPO) requires maintainer branch verification and a signed Stage 7 gate receipt."
          exit 1

      - name: Checkout Code
        uses: actions/checkout@v7
        with:
          fetch-depth: 0
          persist-credentials: false

      - name: Enforce Branch Flow Policy
        if: github.event_name == 'pull_request' && github.base_ref == 'main'
        env:
          HEAD_REF: \${{ github.head_ref }}
          PR_HEAD_REPO: \${{ github.event.pull_request.head.repo.full_name }}
          BASE_REPO: \${{ github.repository }}
        run: |
          if [ "$PR_HEAD_REPO" != "$BASE_REPO" ] || [ "$HEAD_REF" != "develop" ]; then
            echo "::error::Pull requests targeting 'main' must originate exclusively from same-repo 'develop' (got '$PR_HEAD_REPO:$HEAD_REF')."
            exit 1
          fi

      - name: Setup Node.js Runtime
        uses: actions/setup-node@v7
        with:
          node-version: "lts/*"${cacheLine}

      - name: Verify Signed Stage 7 Gate Receipt
        if: github.event_name == 'pull_request' && github.event.pull_request.head.repo.full_name == github.repository
        env:
          SDLC_RECEIPT_KEY: \${{ secrets.SDLC_RECEIPT_KEY }}
          PR_HEAD_SHA: \${{ github.event.pull_request.head.sha }}
          BASE_REF: \${{ github.base_ref }}
          GITHUB_HEAD_REF: \${{ github.head_ref }}
        run: |
          if [ -z "$SDLC_RECEIPT_KEY" ]; then
            echo "::error::Missing SDLC_RECEIPT_KEY secret: configure repository secret SDLC_RECEIPT_KEY to verify Stage 7 gate receipts."
            exit 1
          fi
          TRUSTED_DIR="\${RUNNER_TEMP:-/tmp}/sdlc-trusted-verifier"
          rm -rf "$TRUSTED_DIR" && mkdir -p "$TRUSTED_DIR"
          if git cat-file -e "origin/$BASE_REF:.agent/scripts/sdlc-engine.mjs" 2>/dev/null; then
            git archive "origin/$BASE_REF" .agent/scripts | tar -x -C "$TRUSTED_DIR"
            ENGINE_BIN="$TRUSTED_DIR/.agent/scripts/sdlc-engine.mjs"
          elif [ -f ".agent/scripts/sdlc-engine.mjs" ]; then
            ENGINE_BIN=".agent/scripts/sdlc-engine.mjs"
          else
            echo "::error::Missing .agent/scripts/sdlc-engine.mjs; refusing unverified pull request."
            exit 1
          fi
          if [ "$BASE_REF" = "main" ]; then
            node "$ENGINE_BIN" guard verify --sha "$PR_HEAD_SHA"
          else
            node "$ENGINE_BIN" guard verify --sha "$PR_HEAD_SHA" --branch "$GITHUB_HEAD_REF"
          fi

      - name: Install Dependencies
        run: |
          if [ -f "package-lock.json" ]; then
            npm ci --no-audit --no-fund
          elif [ -f "package.json" ]; then
            npm install --no-audit --no-fund
          fi

      - name: Verify Env-Isolated Test Suite
        if: hashFiles('package.json') != ''
        env:
          SDLC_RECEIPT_KEY: ci-dummy-test-key
        run: |
          npm test

      - name: Verify Universal Quality Gate & Hash-Chain Audit Ledger
        run: |
          if [ -f ".agent/scripts/sdlc-engine.mjs" ]; then
            node .agent/scripts/sdlc-engine.mjs config check
            node .agent/scripts/sdlc-engine.mjs verify --chain-only
            node .agent/scripts/sdlc-engine.mjs skill-audit
            node .agent/scripts/sdlc-engine.mjs gate --no-cache
          else
            npm test
          fi
`;
}

function isLegacySdlcWorkflow(raw = '') {
  if (!raw.includes('sdlc-engine.mjs')) return false;
  const iVerify = raw.indexOf('Verify Signed Stage 7 Gate Receipt');
  const iInstall = raw.indexOf('Install Dependencies');
  return (
    !raw.includes('--branch "$GITHUB_HEAD_REF"') ||
    raw.includes('gate --strict') ||
    !raw.includes('git archive "origin/$BASE_REF"') ||
    /\bnode "\$ENGINE_BIN" verify --sha\b/.test(raw) ||
    !raw.includes('persist-credentials: false') ||
    (iVerify !== -1 && iInstall !== -1 && iInstall < iVerify)
  );
}

function workflowNeedsUpgrade(raw = '', repoRoot = null) {
  if (isLegacySdlcWorkflow(raw)) return true;
  if (!raw.includes('sdlc-engine.mjs')) return false;
  const declaredCache = (/^\s+cache: '(\w+)'$/m.exec(raw) || [])[1] || null;
  return declaredCache !== detectNodeCache(repoRoot);
}

export function installCIWorkflow({ repoRoot = '.', force = false, upgradeLegacy = false } = {}) {
  const wfPath = path.resolve(repoRoot, '.github/workflows/sdlc-quality-gate.yml');
  const exists = fileExists(wfPath);
  if (exists && !force) {
    const existingRaw = readFileSafe(wfPath) || '';
    if (!upgradeLegacy || !workflowNeedsUpgrade(existingRaw, repoRoot)) {
      return { installed: false, upgraded: false, skipped: true, path: wfPath };
    }
  }
  let config = null;
  try {
    ({ config } = loadConfig(repoRoot));
  } catch {
    config = null; // malformed config: fall back to workflow defaults; `config check` reports the error
  }
  const content = buildQualityGateWorkflow({
    runsOn: config?.ci?.runsOn || "${{ vars.SDLC_RUNS_ON || 'ubuntu-latest' }}",
    checkName: config?.ci?.checkName || DEFAULT_QUALITY_GATE_CHECK,
    repoRoot
  });
  writeFileAtomic(wfPath, content);
  return { installed: !exists, upgraded: exists, skipped: false, path: wfPath };
}

export function scaffoldArchlensPolicy(repoRoot = '.', { force = false } = {}) {
  const policyPath = path.resolve(repoRoot, '.archlens/policy.json');
  if (fileExists(policyPath) && !force) {
    return { created: false, path: policyPath };
  }
  const defaultPolicy = {
    title: path.basename(path.resolve(repoRoot)) || 'project',
    src: 'src',
    hierarchical: true,
    order: ['domain', 'application', 'adapters', 'entrypoints'],
    levels: [['src/domain/**'], ['src/application/**'], ['src/adapters/**'], ['src/entrypoints/**']],
    omit: ['node_modules', '.git', 'coverage', 'reports', 'dist', 'build', 'target']
  };
  writeFileAtomic(policyPath, JSON.stringify(defaultPolicy, null, 2) + '\n');
  return { created: true, path: policyPath };
}

export function runDoctor({ repoRoot = '.', fix = false } = {}) {
  const absRoot = path.resolve(repoRoot);
  const nodeMajor = Number(process.versions.node.split('.')[0]) || 0;
  const nodeOk = nodeMajor >= 22;
  const gitOk = gitOutput(['--version'], absRoot) !== null;

  const cfgPath = path.join(absRoot, '.agent/sdlc-config.json');
  let cfgCheck = validateConfigFile(absRoot);
  if (fix) {
    if (!fileExists(cfgPath)) {
      writeFileAtomic(cfgPath, JSON.stringify(generateConfig(absRoot), null, 2) + '\n');
      cfgCheck = validateConfigFile(absRoot);
    } else if (cfgCheck.valid && cfgCheck.warnings.length > 0) {
      const raw = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
      const upgraded = upgradeConfigToV010(raw);
      if (upgraded) writeFileAtomic(cfgPath, JSON.stringify(upgraded, null, 2) + '\n');
      cfgCheck = validateConfigFile(absRoot);
    }
  }

  const policyPath = path.join(absRoot, '.archlens/policy.json');
  if (fix && !fileExists(policyPath)) {
    scaffoldArchlensPolicy(absRoot, { force: false });
  }
  const policyOk = fileExists(policyPath);

  if (fix) {
    upsertGitignore(absRoot);
  }
  const gitignore = inspectGitignore(absRoot);

  if (fix && fileExists(path.join(absRoot, '.git'))) {
    installHooks({ repoRoot: absRoot });
  }
  const hooks = inspectHooks(absRoot);

  const wfPath = path.join(absRoot, '.github/workflows/sdlc-quality-gate.yml');
  if (fix) {
    installCIWorkflow({ repoRoot: absRoot, force: false, upgradeLegacy: true });
  }
  const wfExists = fileExists(wfPath);
  const wfLegacy = wfExists && workflowNeedsUpgrade(readFileSafe(wfPath) || '', absRoot);

  if (fix && process.platform !== 'win32') {
    const commonRoot = resolveGitCommonRepoRoot(absRoot);
    const keyPath = fileExists(path.join(absRoot, '.agent/.receipt-key'))
      ? path.join(absRoot, '.agent/.receipt-key')
      : path.join(commonRoot, '.agent/.receipt-key');
    if (fileExists(keyPath)) {
      try { fs.chmodSync(keyPath, 0o600); } catch {}
    }
  }
  const keyInfo = inspectReceiptKeyStatus(absRoot);
  const ciSecretHint = wfExists
    ? "Provision CI secret with: tr -d '\\r\\n' < .agent/.receipt-key | gh secret set SDLC_RECEIPT_KEY"
    : null;

  const skills = auditSkills(absRoot);
  const auditChain = verifyAuditChain(absRoot);

  const passed =
    nodeOk &&
    gitOk &&
    cfgCheck.valid &&
    policyOk &&
    gitignore.criticalOk &&
    hooks.upToDate &&
    wfExists &&
    !wfLegacy &&
    !keyInfo.committed &&
    !keyInfo.error &&
    skills.passed &&
    auditChain.valid;

  return {
    passed,
    nodeVersion: process.version,
    nodeOk,
    gitOk,
    config: cfgCheck,
    policyOk,
    gitignore,
    hooks,
    workflow: { exists: wfExists, legacyNeedsUpgrade: wfLegacy, path: '.github/workflows/sdlc-quality-gate.yml' },
    receiptKey: { ...keyInfo, ciSecretHint },
    skills,
    auditChain: {
      valid: auditChain.valid,
      recordsCount: auditChain.recordsCount,
      gateReceiptsCount: auditChain.gateReceiptsCount,
      error: auditChain.error || null
    }
  };
}

function promptLine(rl, question) {
  return new Promise((resolve) => {
    rl.question(question, (answer) => resolve(String(answer || '').trim()));
  });
}

async function resolveSelectedAgents({ agents, yes, input, output }) {
  if (agents) return normalizeAgentList(agents);
  const inStream = input || process.stdin;
  const outStream = output || process.stdout;
  if (yes || (!input && !inStream.isTTY)) {
    return ['antigravity', 'claude', 'cursor'];
  }
  const rl = readline.createInterface({ input: inStream, output: outStream });
  try {
    const ans = await promptLine(
      rl,
      `Select AI agents to configure (${SUPPORTED_AGENTS.join(', ')}, or all) [antigravity,claude,cursor]: `
    );
    return normalizeAgentList(ans || 'antigravity,claude,cursor');
  } finally {
    rl.close();
  }
}

function pruneRetiredSkillsInDir(skillsParentDir, baseRoot = null) {
  if (baseRoot) assertNoSymlinkAncestors(baseRoot, skillsParentDir);
  if (!fileExists(skillsParentDir)) return;
  for (const retired of RETIRED_SKILLS) {
    safeRemoveDir(path.join(skillsParentDir, retired), baseRoot);
  }
}

function updateClaudeSettingsJson(settingsPath, warnings, baseRoot = null) {
  const target = resolveUserFileTarget(settingsPath, baseRoot, warnings);
  if (!fileExists(target)) {
    writeFileAtomic(target, JSON.stringify({ permissions: { allow: [...CLAUDE_SDLC_ALLOW_RULES] } }, null, 2) + '\n');
    return;
  }
  let parsed;
  try {
    parsed = JSON.parse(readFileSafe(target) || '{}');
  } catch {
    warnings.push(`Malformed JSON in '${settingsPath}'; left untouched so user configuration is not lost.`);
    return;
  }
  const allow = parsed?.permissions?.allow;
  if (!Array.isArray(allow) || !allow.includes(LEGACY_CLAUDE_WILDCARD)) return;
  const kept = allow.filter((r) => r !== LEGACY_CLAUDE_WILDCARD);
  parsed.permissions.allow = [...kept, ...CLAUDE_SDLC_ALLOW_RULES.filter((r) => !kept.includes(r))];
  writeFileAtomic(target, JSON.stringify(parsed, null, 2) + '\n');
  warnings.push(`Replaced legacy '${LEGACY_CLAUDE_WILDCARD}' in '${settingsPath}' with read/measure-only rules; approvals now prompt.`);
}

export async function installFramework({
  targetDir = '.',
  sourceRoot = PACKAGE_ROOT,
  agents = null,
  globalMode = false,
  homeDir = null,
  force = false,
  yes = false,
  input = null,
  output = null,
  fsImpl = fs
} = {}) {
  const absTarget = path.resolve(targetDir);
  const absSource = path.resolve(sourceRoot);
  const selectedAgents = await resolveSelectedAgents({ agents, yes, input, output });
  const warnings = [];
  const errors = [];
  const rulesBlock = buildRulesBlock();

  if (globalMode) {
    const resolvedHome = path.resolve(homeDir || os.homedir());
    const globalRoot = path.join(resolvedHome, '.agentic-sdlc');
    safeCopyDir(path.join(absSource, '.agent/scripts'), path.join(globalRoot, 'scripts'), { chmodExecutable: true, errors, fsImpl });
    safeCopyDir(path.join(absSource, '.agent/schemas'), path.join(globalRoot, 'schemas'), { chmodExecutable: false, errors, fsImpl });

    const defaultHome = path.resolve(os.homedir());
    const globalEnginePath =
      process.platform !== 'win32' && resolvedHome === defaultHome
        ? '$HOME/.agentic-sdlc/scripts/sdlc-engine.mjs'
        : path.join(globalRoot, 'scripts', 'sdlc-engine.mjs');

    const agentSkillDirs = {
      antigravity: path.join(resolvedHome, '.gemini/antigravity/skills'),
      claude: path.join(resolvedHome, '.claude/skills'),
      cursor: path.join(resolvedHome, '.cursor/skills'),
      codex: path.join(resolvedHome, '.codex/skills'),
      copilot: path.join(resolvedHome, '.copilot/skills')
    };

    for (const agent of selectedAgents) {
      const dstBase = agentSkillDirs[agent];
      if (!dstBase) continue;
      pruneRetiredSkillsInDir(dstBase);
      for (const skillId of CANONICAL_SKILLS) {
        const raw = readFileSafe(path.join(absSource, '.agent/skills', skillId, 'SKILL.md'));
        if (!raw) continue;
        safeWriteFile(
          path.join(dstBase, skillId, 'SKILL.md'),
          adaptSkillContent(raw, agent, { globalEnginePath })
        );
      }
      if (agent === 'claude') {
        upsertMarkedRulesFile(path.join(resolvedHome, '.claude/CLAUDE.md'), rulesBlock, resolvedHome, warnings);
        updateClaudeSettingsJson(path.join(resolvedHome, '.claude/settings.json'), warnings, resolvedHome);
      }
    }

    return {
      success: errors.length === 0,
      globalMode: true,
      homeDir: resolvedHome,
      agents: selectedAgents,
      warnings,
      errors
    };
  }

  // Local repository installation
  if (absSource !== absTarget) {
    safeCopyDir(path.join(absSource, '.agent/scripts'), path.join(absTarget, '.agent/scripts'), { chmodExecutable: true, errors, fsImpl, baseRoot: absTarget });
    safeCopyDir(path.join(absSource, '.agent/schemas'), path.join(absTarget, '.agent/schemas'), { chmodExecutable: false, errors, fsImpl, baseRoot: absTarget });
    safeCopyDir(path.join(absSource, 'docs/templates'), path.join(absTarget, 'docs/templates'), { chmodExecutable: false, errors, fsImpl, baseRoot: absTarget });
  }

  pruneRetiredSkillsInDir(path.join(absTarget, '.agent/skills'), absTarget);
  for (const skillId of CANONICAL_SKILLS) {
    const srcSkillPath = path.join(absSource, '.agent/skills', skillId, 'SKILL.md');
    const dstSkillPath = path.join(absTarget, '.agent/skills', skillId, 'SKILL.md');
    if (fileExists(srcSkillPath) && srcSkillPath !== dstSkillPath) {
      safeWriteFile(dstSkillPath, fs.readFileSync(srcSkillPath, 'utf8'), undefined, absTarget);
    }
  }

  // Never silently replace an existing config: invalid ones are left untouched unless --force (which backs up first).
  const cfgPath = path.join(absTarget, '.agent/sdlc-config.json');
  assertNoSymlinkAncestors(absTarget, path.dirname(cfgPath));
  const cfgExists = fileExists(cfgPath);
  const cfgCheck = cfgExists && !force ? validateConfigFile(absTarget) : null;
  if (cfgExists && force) fs.copyFileSync(cfgPath, `${cfgPath}.bak`);
  if (!cfgExists || force) {
    writeFileAtomic(cfgPath, JSON.stringify(generateConfig(absTarget), null, 2) + '\n');
  } else if (!cfgCheck.valid) {
    warnings.push(`Invalid .agent/sdlc-config.json left untouched: ${cfgCheck.errors.join('; ')}; fix it or rerun with --force to regenerate (a .bak copy is kept).`);
  }
  upsertGitignore(absTarget, { warnings });

  assertNoSymlinkAncestors(absTarget, path.join(absTarget, '.archlens'));
  scaffoldArchlensPolicy(absTarget, { force: false });
  if (fileExists(path.join(absTarget, '.git'))) {
    installHooks({ repoRoot: absTarget, fsImpl });
  }
  assertNoSymlinkAncestors(absTarget, path.join(absTarget, '.github/workflows'));
  installCIWorkflow({ repoRoot: absTarget, force, upgradeLegacy: true });

  upsertMarkedRulesFile(path.join(absTarget, 'AGENTS.md'), rulesBlock, absTarget, warnings);

  for (const agent of selectedAgents) {
    if (agent === 'claude') {
      pruneRetiredSkillsInDir(path.join(absTarget, '.claude/skills'), absTarget);
      for (const skillId of CANONICAL_SKILLS) {
        const raw = readFileSafe(path.join(absTarget, '.agent/skills', skillId, 'SKILL.md'));
        if (raw) safeWriteFile(path.join(absTarget, '.claude/skills', skillId, 'SKILL.md'), adaptSkillContent(raw, 'claude'), undefined, absTarget);
      }
      upsertMarkedRulesFile(path.join(absTarget, 'CLAUDE.md'), rulesBlock, absTarget, warnings);
      updateClaudeSettingsJson(path.join(absTarget, '.claude/settings.json'), warnings, absTarget);
    } else if (agent === 'cursor') {
      pruneRetiredSkillsInDir(path.join(absTarget, '.cursor/skills'), absTarget);
      // Remove legacy duplicate per-skill .mdc files
      const rulesDir = path.join(absTarget, '.cursor/rules');
      assertNoSymlinkAncestors(absTarget, rulesDir);
      if (fileExists(rulesDir)) {
        for (const name of fs.readdirSync(rulesDir)) {
          if (/^sdlc.*\.mdc$/i.test(name)) safeRemoveDir(path.join(rulesDir, name), absTarget);
        }
      }
      for (const skillId of CANONICAL_SKILLS) {
        const raw = readFileSafe(path.join(absTarget, '.agent/skills', skillId, 'SKILL.md'));
        if (raw) safeWriteFile(path.join(absTarget, '.cursor/skills', skillId, 'SKILL.md'), adaptSkillContent(raw, 'cursor'), undefined, absTarget);
      }
      safeWriteFile(
        path.join(absTarget, '.cursor/rules/agentic-sdlc.mdc'),
        `---\ndescription: "Agentic SDLC v0.1.0 Governance Rules"\nalwaysApply: true\n---\n\n${rulesBlock}\n`,
        undefined,
        absTarget
      );
    } else if (agent === 'codex') {
      pruneRetiredSkillsInDir(path.join(absTarget, '.codex/skills'), absTarget);
      for (const skillId of CANONICAL_SKILLS) {
        const raw = readFileSafe(path.join(absTarget, '.agent/skills', skillId, 'SKILL.md'));
        if (raw) safeWriteFile(path.join(absTarget, '.codex/skills', skillId, 'SKILL.md'), adaptSkillContent(raw, 'codex'), undefined, absTarget);
      }
    } else if (agent === 'copilot') {
      upsertMarkedRulesFile(path.join(absTarget, '.github/copilot-instructions.md'), rulesBlock, absTarget, warnings);
    }
  }

  return {
    success: errors.length === 0,
    globalMode: false,
    targetDir: absTarget,
    agents: selectedAgents,
    warnings,
    errors
  };
}
